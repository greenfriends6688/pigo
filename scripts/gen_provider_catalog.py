#!/usr/bin/env python3
"""Generate internal/models/catalog_gen.go from pi's bundled model catalog.

The app shows pi's own provider list — the one `/model` and `/login` offer —
instead of the handful of providers in `~/.pi/agent/models-store.json`. The
data comes from the SDK package `@earendil-works/pi-ai`, whose
`dist/providers/data/<id>.json` files hold every chat model with its API,
base URL and capabilities, and whose `dist/providers/<id>.js` files name the
provider and say whether it also signs in with OAuth.

Run it when pi is upgraded:

    python3 scripts/gen_provider_catalog.py \
        /path/to/node_modules/@earendil-works/pi-ai/dist/providers
"""

import json
import os
import re
import sys

HEADER = """// Code generated by scripts/gen_provider_catalog.py from pi's bundled model
// catalog; DO NOT EDIT.
//
// It is pi's provider list, which `/model` and `/login` offer: the app's
// "添加 Provider" picker reads it so a provider the SDK ships is one press
// away, not something the user has to know by id.
"""


def provider_label(src, pid):
    """The provider's display name and OAuth flag from its module."""
    name = pid
    oauth = False
    if src:
        # Only the createProvider({...}) block names the provider; the auth
        # methods above it have names of their own ("Anthropic API key").
        at = src.find("createProvider({")
        block = src[at:] if at >= 0 else src
        found = re.search(r"^\s*name:\s*\"([^\"]+)\"", block, re.M)
        if found:
            name = found.group(1)
        oauth = re.search(r"oauth:\s*(lazyOAuth|oauth|\{)", block) is not None
    return name, oauth


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    providers = {}
    for entry in sorted(os.listdir(os.path.join(root, "data"))):
        if not entry.endswith(".json"):
            continue
        with open(os.path.join(root, "data", entry)) as f:
            payload = json.load(f)
        models = []
        for api, bucket in payload.items():
            if not isinstance(bucket, dict):
                continue
            for key, model in bucket.items():
                if not isinstance(model, dict) or model.get("type") != "chat":
                    continue
                pid = model.get("provider")
                if not pid:
                    continue
                models.append(model)
        for model in models:
            pid = model["provider"]
            slot = providers.setdefault(pid, {"models": []})
            if not slot["models"]:
                slot["base_url"] = model.get("baseUrl", "")
                slot["api"] = model.get("api", "")
            slot["models"].append(model)
    ids = sorted(providers)
    out = [HEADER]
    out.append("package models\n")
    out.append("// BuiltinProvider is one provider pi ships, with the models the app")
    out.append("// writes when it is added to models.json.")
    out.append("type BuiltinProvider struct {")
    out.append("\tID, Name, BaseURL, API string")
    out.append("\tOAuth                 bool")
    out.append("\tModels                []BuiltinModel")
    out.append("}\n")
    out.append("// BuiltinModel is one model of a built-in provider: what models.json")
    out.append("// needs to make it selectable, and what the settings page shows.")
    out.append("type BuiltinModel struct {")
    out.append("\tID, Name      string")
    out.append("\tContextWindow int")
    out.append("\tMaxTokens     int")
    out.append("\tReasoning     bool")
    out.append("}\n")
    out.append("// BuiltinProviders is pi's catalog, providers by id.")
    out.append("var BuiltinProviders = []BuiltinProvider{")
    for pid in ids:
        slot = providers[pid]
        src = None
        js = os.path.join(root, pid + ".js")
        if os.path.exists(js):
            with open(js) as f:
                src = f.read()
        name, oauth = provider_label(src, pid)
        out.append("\t{")
        out.append('\t\tID: %s, Name: %s,' % (go(pid), go(name)))
        out.append('\t\tBaseURL: %s, API: %s,' % (go(slot["base_url"]), go(slot["api"])))
        if oauth:
            out.append("\t\tOAuth: true,")
        out.append("\t\tModels: []BuiltinModel{")
        seen = set()
        for model in sorted(slot["models"], key=lambda m: m.get("name", m["id"])):
            mid = model["id"]
            if mid in seen:
                continue
            seen.add(mid)
            out.append("\t\t\t{ID: %s, Name: %s, ContextWindow: %d, MaxTokens: %d%s}," % (
                go(mid), go(model.get("name") or mid), int(model.get("contextWindow") or 0),
                int(model.get("maxTokens") or 0), ", Reasoning: true" if model.get("reasoning") else ""))
        out.append("\t\t},")
        out.append("\t},")
    out.append("}")
    out.append("")
    target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "internal", "models", "catalog_gen.go")
    with open(target, "w") as f:
        f.write("\n".join(out))
    print("wrote", target, "with", len(ids), "providers,",
          sum(len(providers[i]["models"]) for i in ids), "models")


def go(text):
    return json.dumps(str(text), ensure_ascii=False)


if __name__ == "__main__":
    main()
